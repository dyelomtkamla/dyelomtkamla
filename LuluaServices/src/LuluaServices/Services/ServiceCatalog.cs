public record SubService(string Name, string Description);

public record Faq(string Question, string Answer);

public record ServiceSection(
    string Slug, string Icon, string Color, string Name, string Title, string Tagline,
    string Description, string Intro, IReadOnlyList<SubService> Services,
    IReadOnlyList<string> Features, IReadOnlyList<Faq> Faq)
{
    /// <summary>Text the home-page search matches against.</summary>
    public string SearchText => Name + " " + string.Join(" ", Services.Select(s => s.Name));
}
